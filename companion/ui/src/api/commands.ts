// One typed wrapper per Tauri command. The types come from the Rust
// definitions (generated by ts-rs into src/bindings), so a renamed field
// fails the frontend build instead of failing at runtime.

export function appInfo(): Promise<AppInfo> {
  return invoke<AppInfo>("app_info");
}

export function listCharacters(): Promise<CharacterSummary[]> {
  return invoke<CharacterSummary[]>("list_characters");
}

export function characterJournal(characterId: number): Promise<Journal | null> {
  return invoke<Journal | null>("character_journal", { characterId });
}

export function characterMilestones(characterId: number): Promise<Award[]> {
  return invoke<Award[]>("character_milestones", { characterId });
}

/** A character's screenshots by day, matched to the moments the addon took them. */
export function characterScreenshots(
  characterId: number,
): Promise<Record<string, Screenshot[]>> {
  return invoke<Record<string, Screenshot[]>>("character_screenshots", {
    characterId,
  });
}

/** A URL the window may load a local screenshot from. */
export function screenshotUrl(path: string): string {
  return convertFileSrc(path);
}

export function getSettings(): Promise<SettingsView> {
  return invoke<SettingsView>("get_settings");
}

export function saveSettings(settings: Settings): Promise<SyncReport> {
  return invoke<SyncReport>("save_settings", { settings });
}

export function syncNow(): Promise<SyncReport> {
  return invoke<SyncReport>("sync_now");
}

export function deleteCharacter(characterId: number): Promise<void> {
  return invoke<void>("delete_character", { characterId });
}

/** Called whenever a journal is imported, with the character's id (or nothing after a full pass). */
export function onJournalUpdated(
  handler: (characterId: number | null) => void,
): Promise<UnlistenFn> {
  return listen<number | null>("journal-updated", (event) =>
    handler(event.payload ?? null),
  );
}

/** Called whenever the game writes a screenshot. */
export function onScreenshotsUpdated(handler: () => void): Promise<UnlistenFn> {
  return listen("screenshots-updated", () => handler());
}

// ── Writing ──────────────────────────────────────────────────────────────────

/** Every accepted version of a character's days and weeks, newest first within each. */
export function characterStories(characterId: number): Promise<Story[]> {
  return invoke<Story[]>("character_stories", { characterId });
}

/** Finished days and weeks with no accepted entry, or with a draft waiting, newest first. */
export function reviewList(characterId: number): Promise<ReviewItem[]> {
  return invoke<ReviewItem[]>("review_list", { characterId });
}

/** Puts a draft in the journal; the other drafts for that day or week are discarded. */
export function acceptDraft(
  characterId: number,
  storyId: number,
): Promise<boolean> {
  return invoke<boolean>("accept_draft", { characterId, storyId });
}

export function discardDraft(
  characterId: number,
  storyId: number,
): Promise<boolean> {
  return invoke<boolean>("discard_draft", { characterId, storyId });
}

/** Writes days and weeks as drafts ahead of the backlog; a note only for a rewrite. */
export function writeDrafts(
  characterId: number,
  slots: Slot[],
  narrator: string | null,
  note: string | null,
): Promise<void> {
  return invoke<void>("write_drafts", { characterId, slots, narrator, note });
}

export function writingStatus(characterId: number): Promise<WritingStatus> {
  return invoke<WritingStatus>("writing_status", { characterId });
}

/** Writes a day or week (again) ahead of the backlog, with a one-off narrator if given. */
export function writeNow(
  characterId: number,
  kind: StoryKind,
  startDay: string,
  narrator: string | null,
): Promise<void> {
  return invoke<void>("write_now", { characterId, kind, startDay, narrator });
}

/** Writes today as it stands, while it is still going; the full entry still comes once it is
 * over. */
export function writeSoFar(
  characterId: number,
  narrator: string | null,
): Promise<void> {
  return invoke<void>("write_so_far", { characterId, narrator });
}

export function cancelWriting(
  characterId: number,
  kind: StoryKind,
  startDay: string,
): Promise<boolean> {
  return invoke<boolean>("cancel_writing", { characterId, kind, startDay });
}

export function retryWriting(
  characterId: number,
  kind: StoryKind,
  startDay: string,
): Promise<void> {
  return invoke<void>("retry_writing", { characterId, kind, startDay });
}

export function setWritingPaused(paused: boolean): Promise<void> {
  return invoke<void>("set_writing_paused", { paused });
}

export function listNarrators(): Promise<NarratorInfo[]> {
  return invoke<NarratorInfo[]>("list_narrators");
}

/** The player's own narrator, to edit; null once it is gone. */
export function narrator(id: string): Promise<Narrator | null> {
  return invoke<Narrator | null>("narrator", { id });
}

/** Every field of a narrator, as the start of a new one; not saved yet. */
export function copyNarrator(id: string): Promise<Narrator> {
  return invoke<Narrator>("copy_narrator", { id });
}

export function saveNarrator(narrator: Narrator): Promise<NarratorSaved> {
  return invoke<NarratorSaved>("save_narrator", { narrator });
}

/** Adds a shared narrator file, read from where the player picked it. */
export function importNarratorFile(path: string): Promise<NarratorSaved> {
  return invoke<NarratorSaved>("import_narrator_file", { path });
}

/** Writes the narrator as one file into a folder; answers the file's path. */
export function exportNarrator(id: string, folder: string): Promise<string> {
  return invoke<string>("export_narrator", { id, folder });
}

export function deleteNarrator(id: string): Promise<void> {
  return invoke<void>("delete_narrator", { id });
}

/** Writes one day with the narrator being edited, saved or not; nothing is stored. */
export function previewNarrator(
  narrator: Narrator,
  day: PreviewDay,
): Promise<PreviewResult> {
  return invoke<PreviewResult>("preview_narrator", { narrator, day });
}

export function cancelPreview(): Promise<boolean> {
  return invoke<boolean>("cancel_preview");
}

/** Called with the preview's text as it is written. */
export function onNarratorPreview(
  handler: (event: PreviewEvent) => void,
): Promise<UnlistenFn> {
  return listen<PreviewEvent>("narrator-preview", (event) =>
    handler(event.payload),
  );
}

/** Called for everything the background writer does. */
export function onWriting(
  handler: (event: QueueEvent) => void,
): Promise<UnlistenFn> {
  return listen<QueueEvent>("writing", (event) => handler(event.payload));
}

