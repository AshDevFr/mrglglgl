// Writes the milestone reference page from the app's own data: companion/crates/mrglglgl-core/data/
// milestones.toml (ids, rarity, groups from its section comments) and the English names and
// descriptions in companion/ui/src/i18n/locales/en.json. The page is not committed.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(site, "..");
const toml = readFileSync(join(repo, "companion/crates/mrglglgl-core/data/milestones.toml"), "utf8");
const en = JSON.parse(readFileSync(join(repo, "companion/ui/src/i18n/locales/en.json"), "utf8"));

const FIRST_GROUP = "The first stamps";
const groups = [{ title: FIRST_GROUP, items: [] }];
let current = null;
const lines = toml.split("\n");
for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  // A section heading is a comment line followed by a blank line; other comments are notes.
  if (/^# \S/.test(line) && lines[i + 1] === "" && i > 12) {
    groups.push({ title: line.slice(2).trim().replace(/[.:].*$/, "").replace(/\.$/, ""), items: [] });
    continue;
  }
  if (line.trim() === "[[milestone]]") {
    current = { enabled: true };
    groups[groups.length - 1].items.push(current);
    continue;
  }
  const m = current && line.match(/^(\w+)\s*=\s*(.+?)\s*$/);
  if (m) current[m[1]] = m[2].replace(/^"|"$/g, "");
}

const stars = (n) => "★".repeat(n) + "☆".repeat(5 - n);
const esc = (s) => s.replace(/\|/g, "\\|");
let total = 0;
let body = "";
for (const g of groups) {
  const items = g.items.filter((x) => x.enabled !== "false" && x.proposed !== "true");
  if (!items.length) continue;
  body += `## ${g.title}\n\n| Stamp | Earned by | Rarity |\n|---|---|---|\n`;
  for (const x of items) {
    const t = en.milestones[x.id];
    if (!t) throw new Error(`milestones.${x.id} is missing from en.json`);
    body += `| **${esc(t.name)}** | ${esc(t.description)} | ${stars(Number(x.rarity))} |\n`;
    total++;
  }
  body += "\n";
}

const front = `---
title: Every milestone
description: All ${total} milestone stamps, what earns each one, and how rare it is.
---

{/* Generated by scripts/milestones.mjs from the app's milestone data; do not edit by hand. */}

There are ${total} milestones. How they appear on a day, and which ones the narrator hears about, is
in [Reading your journal](/guide/reading/#milestones). Rarity runs from one star (most players earn
it early) to five (few ever will): when a day earns several stamps, the three rarest are pressed on
its page and told to the narrator.

`;
const out = join(site, "src/content/docs/reference");
mkdirSync(out, { recursive: true });
// .mdx for the comment above; the table is plain markdown.
writeFileSync(join(out, "milestones.mdx"), front + body);
console.log(`milestones: ${total} stamps -> reference/milestones`);
